    public List<Experiment> all() {
        return List.copyOf(EXPERIMENTS);
    }

    public List<Experiment> search(ExperimentCategory category, String query) {
        String text = query == null ? "" : query.trim().toLowerCase(Locale.ROOT);
        return EXPERIMENTS.stream()
                .filter(e -> category == null || e.category() == category)
                .filter(e -> text.isEmpty() || e.title().toLowerCase(Locale.ROOT).contains(text)
                        || e.shortDesc().toLowerCase(Locale.ROOT).contains(text)
                        || e.category().label().toLowerCase(Locale.ROOT).contains(text))
                .sorted(Comparator.comparing(Experiment::title))
                .toList();
    }

